"""Validate the complete public research export without external dependencies."""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit, unquote
from html import escape
import argparse
import hashlib
import json
import re
import struct
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


class Page(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids, self.links = [], []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if attrs.get('id'):
            self.ids.append(attrs['id'])
        for key in ('src', 'href', 'poster', 'data-lightbox'):
            if attrs.get(key):
                self.links.append(attrs[key])


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--site', type=Path, default=ROOT/'dist')
    args = parser.parse_args()
    dest = args.site.resolve()
    pages = {}
    markup = {}
    for name in ('index.html', 'analysis.html', 'archive.html'):
        text = (dest/name).read_text(encoding='utf-8')
        page = Page()
        page.feed(text)
        assert len(page.ids) == len(set(page.ids)), 'Duplicate ID: '+name
        assert '@@' not in text and '未公开发布' not in text
        assert not re.search(r'[DF]:[\\/]|Bearer\s|gho_[A-Za-z0-9]{20,}', text), 'Unexpected private material'
        pages[name], markup[name] = page, text
    links = set()
    for name, page in pages.items():
        for href in page.links:
            split = urlsplit(href)
            if split.scheme or split.netloc:
                continue
            if href == '../../index.html':
                continue  # This page is generated by the repository's shared build.
            target = (dest/unquote(split.path)).resolve() if split.path else dest/name
            assert target.is_relative_to(dest), 'Unexpected external local path: '+href
            assert target.is_file(), 'Missing resource: '+name+' -> '+href
            if split.fragment and target.name in pages:
                assert unquote(split.fragment) in pages[target.name].ids, 'Missing anchor: '+href
            links.add(target.relative_to(dest).as_posix())
    data = json.loads((ROOT/'analysis.json').read_text(encoding='utf-8'))
    for entry in data['dialogue']:
        for key in ('quote', 'analysis', 'consequence'):
            assert escape(entry[key], quote=True) in markup['analysis.html']
    order = ['overview', 'reference-analysis', 'understanding', 'principle', 'creative-path', 'watch']
    assert [markup['index.html'].index('id="'+key+'"') for key in order] == sorted(markup['index.html'].index('id="'+key+'"') for key in order)
    assert data['reference']['url'] in markup['index.html']
    production = json.loads((ROOT/'production.json').read_text(encoding='utf-8'))
    assert len({x['task_id'] for x in production['shots']}) == 6
    assert sum(x['credits'] for x in production['shots']) == 975
    media = json.loads((ROOT/'assets/media-manifest.json').read_text(encoding='utf-8'))
    for entry in media['videos'] + media['stills']:
        assert digest(dest/'assets'/entry['file']) == entry['sha256']
    for key in ('reference', 'source_reference'):
        assert digest(dest/'assets'/media[key]['file']) == media[key]['sha256']
    guide = json.loads((ROOT/'assets/understanding-map-manifest.json').read_text(encoding='utf-8'))
    for entry in guide['source_files']:
        assert digest(ROOT/entry['file']) == entry['sha256']
    for entry in guide['files']:
        assert digest(dest/'assets'/entry['file']) == entry['sha256']
    png = dest/'assets/understanding-map-v1.png'
    assert struct.unpack('>II', png.read_bytes()[16:24]) == (2400, 5166)
    ET.fromstring((dest/'assets/understanding-map-v1.svg').read_text(encoding='utf-8'))
    registry = json.loads((ROOT.parents[1]/'projects.json').read_text(encoding='utf-8'))
    entry = next(x for x in registry['projects'] if x['id'] == '0020')
    assert entry['preview']['path'].endswith('/assets/understanding-map-v1.png')
    for keyword in ('开窗', '拍摄', '创作'):
        assert keyword in entry['summary']
    assert entry['source_url'] == data['reference']['url']
    config = json.loads((ROOT/'publication.json').read_text(encoding='utf-8'))
    assert digest(png) == config['guide']['sha256'], 'The original delivered guide must remain unchanged'
    total = sum(p.stat().st_size for p in dest.rglob('*') if p.is_file())
    assert total < 60_000_000, 'Publication budget exceeded'
    result = {'status':'passed','pages':len(pages),'local_resources':len(links),'videos':len(media['videos']),
              'guide_dimensions':[2400,5166],'original_guide_preserved':True,'total_bytes':total,
              'dialogue_records':len(data['dialogue']),'total_generation_credits':975,
              'new_generation_credits':0,'private_path_scan':'passed'}
    (ROOT/'publication-checks.json').write_text(json.dumps(result, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(result, ensure_ascii=False))


if __name__ == '__main__':
    main()
