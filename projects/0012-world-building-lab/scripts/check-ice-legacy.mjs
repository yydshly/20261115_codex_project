import assert from 'node:assert/strict';
import {register} from 'node:module';
import {buildIceAge,iceAgeFrame} from '../web/ice-age.js';
import {drownedShelfDistance,legacyCrossSection,legacyPeriods,legacyReading,makeLegacySurvey} from '../web/ice-legacy.js';
import {buildWorldWaterBalance} from '../web/watershed-world.js';
import {buildWetlandModel} from '../web/wetland-layout.js';
import {terrainHeight} from '../web/large-world.js';
import {gapFor} from '../web/environment-gaps.js';

register('./three-test-loader.mjs',import.meta.url);
const {Scene,Object3D}=await import('three');
const {createIceAgeScene}=await import('../web/ice-age-scene.js');
const {createLegacyScene}=await import('../web/ice-legacy-scene.js');
const model=buildIceAge(),survey=makeLegacySurvey(model);
const frames=Object.fromEntries(legacyPeriods.map(k=>[k,iceAgeFrame(model,k)]));
const find=id=>survey.stops.find(p=>p.id===id);
const read=(id,period)=>legacyReading(model,frames[period],find(id));
assert.equal(survey.stops.length,8);
assert.ok(read('ice-edge','glacial').ice>40&&read('ice-edge','now').ice<.01);
assert.ok(read('moraine','glacial').ice>3&&read('moraine','early').ice<1.7);
assert.equal(read('lake','glacial').lake,false);
assert.ok(read('lake','holocene').lake&&read('lake','now').lake);
assert.ok(!read('outer','glacial').ocean&&!read('outer','early').ocean&&read('outer','pulse').ocean);
assert.ok(!read('inner','pulse').ocean&&read('inner','warming').ocean);
assert.ok(read('inner','now').fill>5&&read('outer','now').fill>8);
assert.equal(read('wetland','now').status,'现代湿地低滩');
assert.ok(!read('valley','glacial').ocean&&!read('valley','now').ocean);
const drown=legacyPeriods.map(id=>drownedShelfDistance(survey,frames[id]));
assert.equal(drown[0],0);
assert.ok(drown[2]>0&&drown[2]<drown[3]&&drown[3]<drown.at(-1));
assert.ok(drown.every((n,i)=>!i||n>=drown[i-1]));
const cross=legacyCrossSection(survey,find('outer')),center=cross[33];
assert.ok(center.now-center.former>8&&center.former<cross[0].former-3&&center.former<cross.at(-1).former-3);

const scene=new Scene(),land=new Object3D(),sea=new Object3D();
scene.add(land,sea);
const timeline=createIceAgeScene(scene,[land,sea],sea);
let wetlands;
const controller=createLegacyScene(scene,timeline,()=>wetlands??=buildWetlandModel(buildWorldWaterBalance(),terrainHeight));
const stations=controller.prepare().stops;
const stop=id=>stations.find(p=>p.id===id);
controller.show('glacial',stop('moraine'),false,true);
assert.ok(!land.visible&&!sea.visible);
const root=scene.getObjectByName('glacial landform legacy survey'),ridge=root.getObjectByName('old moraine gravel ridge');
assert.equal(ridge.visible,false);
controller.show('early',stop('moraine'),true,true);
assert.ok(ridge.visible&&ridge.children.length===2);
controller.show('now',stop('outer'),true,true);
const section=root.getObjectByName('legacy sediment cross section outer');
assert.ok(land.visible&&!sea.visible&&section.visible);
controller.show('now',stop('wetland'),true,true);
assert.ok(sea.visible&&!section.visible&&wetlands.stations.length===4);
const aerial=controller.show('pulse',stop('outer'),true,true);
assert.ok(aerial.observed.ocean&&aerial.cutaway);
root.traverse(o=>{
  for(const attr of Object.values(o.geometry?.attributes??{}))assert.ok(attr.array.every(Number.isFinite));
});
controller.hide();
assert.ok(land.visible&&sea.visible&&!root.visible);
timeline.show('glacial',true,'water');
assert.ok(!land.visible&&!sea.visible,'legacy does not change the ordinary timeline');
timeline.hide();
assert.equal(gapFor('ice-age-legacy').sample.mode,'legacy');
console.log('8 stations, inherited ice retreat, staged shelf flooding, cross-cut fill, wetland bands and timeline restoration passed.');
console.log('Submerged shelf section (m):',drown.map(Math.round));
